"""The intermediates lab of the CI is gone: the security state replaced it (scripts/ci_lab_security_state.py, ci/security-state/).

The core no longer declares an intermediates list: it copies a ready security state (intermediates, OneCRL and the CRLite filters, generated by the
engine) into every profile, and a CI leg points STEALTHFOX_SECURITY_STATE at a fixed directory of the repository. A leftover of the old lab (the
script, its pinned list, a workflow that still exports STEALTHFOX_INTERMEDIATES) would be a second road that nothing reads. The file keeps its name
because ci/required-suites.json only grows (scripts/ci_verdict.py, against main): its tests now guard that the old road stays gone.
"""
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]


def test_the_files_of_the_intermediates_lab_are_gone():
    for rel in ("scripts/ci_lab_intermediates.py", "ci/intermediates.json", "ci/intermediates.pin.json"):
        assert not (ROOT / rel).exists(), "%s is a leftover of the intermediates lab" % rel


def test_no_workflow_names_the_intermediates_lab():
    for wf in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        text = wf.read_text(encoding="utf-8")
        for word in ("STEALTHFOX_INTERMEDIATES", "ci_lab_intermediates", "intermediates.pin.json"):
            assert word not in text, "%s still names %s" % (wf.name, word)
